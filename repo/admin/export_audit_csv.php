<?php
require_once __DIR__ . '/../includes/functions.php';
require_role('admin');

$action_filter = $_GET['action_filter'] ?? '';
$user_filter   = $_GET['user'] ?? '';
$entity_filter = $_GET['entity'] ?? '';
$search        = trim($_GET['search'] ?? '');
$date_from     = $_GET['date_from'] ?? '';
$date_to       = $_GET['date_to'] ?? '';

$where = "WHERE 1=1";
$params = [];

if ($action_filter !== '') { $where .= " AND a.action = ?";      $params[] = $action_filter; }
if ($user_filter !== '')   { $where .= " AND a.user_id = ?";     $params[] = (int) $user_filter; }
if ($entity_filter !== '') { $where .= " AND a.entity_type = ?"; $params[] = $entity_filter; }
if ($date_from !== '')     { $where .= " AND DATE(a.created_at) >= ?"; $params[] = $date_from; }
if ($date_to !== '')       { $where .= " AND DATE(a.created_at) <= ?"; $params[] = $date_to; }
if ($search !== '') {
    $where .= " AND (a.details LIKE ? OR a.actor_name LIKE ? OR a.ip_address LIKE ? OR a.old_value LIKE ? OR a.new_value LIKE ?)";
    for ($i = 0; $i < 5; $i++) { $params[] = "%$search%"; }
}

$stmt = $pdo->prepare("
    SELECT a.*, u.email AS user_email, u.staff_id AS user_staff_id
    FROM audit_log a
    LEFT JOIN users u ON a.user_id = u.user_id
    $where
    ORDER BY a.created_at ASC, a.id ASC
");
$stmt->execute($params);
$logs = $stmt->fetchAll();

$admin = current_user();
// The export itself is an auditable event.
audit_log($pdo, $admin['user_id'], 'report_exported',
    'Exported audit log as CSV (' . count($logs) . ' entries)', 'audit_log', null, null,
    ['filters' => array_filter([
        'action' => $action_filter, 'user' => $user_filter, 'entity' => $entity_filter,
        'search' => $search, 'date_from' => $date_from, 'date_to' => $date_to,
    ], fn($v) => $v !== '')]);

header('Content-Type: text/csv; charset=utf-8');
header('Content-Disposition: attachment; filename="helpdeskpro-audit-log-' . date('Y-m-d-His') . '.csv"');

$out = fopen('php://output', 'w');

// Provenance header so the export is self-describing for an auditor
fputcsv($out, ['HelpDeskPro Audit Log Export']);
fputcsv($out, ['Generated at', date('Y-m-d H:i:s')]);
fputcsv($out, ['Generated by', $admin['name'] . ' (' . $admin['role'] . ')']);
fputcsv($out, ['Entries', count($logs)]);
fputcsv($out, []);

fputcsv($out, [
    'Entry ID', 'Timestamp (UTC offset per server)', 'Action', 'Actor Name', 'Actor Role',
    'Actor Email', 'Actor Staff ID', 'Actor User ID', 'Record Type', 'Record ID',
    'Details', 'Before', 'After', 'IP Address', 'User Agent',
]);

foreach ($logs as $l) {
    fputcsv($out, [
        $l['id'],
        $l['created_at'],
        $l['action'],
        $l['actor_name'] ?? 'Anonymous',
        $l['actor_role'] ?? '',
        $l['user_email'] ?? '',
        $l['user_staff_id'] ?? '',
        $l['user_id'] ?? '',
        $l['entity_type'] ?? '',
        $l['entity_id'] ?? '',
        $l['details'] ?? '',
        $l['old_value'] ?? '',
        $l['new_value'] ?? '',
        $l['ip_address'],
        $l['user_agent'] ?? '',
    ]);
}
fclose($out);
exit;
