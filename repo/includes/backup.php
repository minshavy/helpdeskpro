<?php
/**
 * Database backup generator
 * ---------------------------------------------------------
 * Produces a complete, restorable .sql dump using only PHP and PDO.
 * Shared hosts like InfinityFree don't allow the mysqldump command, so
 * this reads each table's structure and rows directly.
 *
 * Output is streamed through $write one piece at a time rather than built
 * up as one giant string, so a large database can't exhaust PHP's memory.
 */

/**
 * Tables are dumped in dependency order so the file restores cleanly even
 * without disabling foreign key checks. Any table not listed here (e.g. one
 * added later) is still included, just appended at the end.
 */
function backup_table_order($pdo) {
    $preferred = [
        'departments', 'staff_id_sequence', 'users', 'tickets', 'ticket_logs', 'login_attempts',
        'audit_log', 'password_resets', 'canned_responses', 'kb_articles', 'notifications',
    ];
    $existing = $pdo->query("SHOW TABLES")->fetchAll(PDO::FETCH_COLUMN);
    $ordered = array_values(array_intersect($preferred, $existing));
    foreach ($existing as $t) {
        if (!in_array($t, $ordered, true)) {
            $ordered[] = $t;
        }
    }
    return $ordered;
}

/** Quote a single value as a SQL literal, keeping NULL as NULL. */
function backup_sql_value($pdo, $value) {
    if ($value === null) {
        return 'NULL';
    }
    return $pdo->quote((string) $value);
}

/**
 * Write a full dump through the $write callback.
 *
 * @param PDO      $pdo
 * @param callable $write     receives each chunk of SQL text
 * @param string   $generatedBy  name recorded in the file header
 * @return array   ['tables' => n, 'rows' => n] summary
 */
function generate_sql_backup($pdo, callable $write, $generatedBy = 'system') {
    $tables = backup_table_order($pdo);
    $dbName = $pdo->query("SELECT DATABASE()")->fetchColumn();
    $totalRows = 0;

    $write("-- =========================================================\n");
    $write("-- HelpDeskPro database backup\n");
    $write("-- Database   : $dbName\n");
    $write("-- Generated  : " . date('Y-m-d H:i:s') . "\n");
    $write("-- Generated by: $generatedBy\n");
    $write("-- Tables     : " . count($tables) . "\n");
    $write("--\n");
    $write("-- TO RESTORE: open phpMyAdmin for your database -> Import -> choose\n");
    $write("-- this file. It drops and recreates every table, so it REPLACES the\n");
    $write("-- current contents with the contents of this backup.\n");
    $write("--\n");
    $write("-- CONTAINS SENSITIVE DATA: password hashes and 2FA secrets. Store it\n");
    $write("-- somewhere private and never commit it to a public repository.\n");
    $write("-- =========================================================\n\n");

    $write("SET NAMES utf8mb4;\n");
    $write("SET FOREIGN_KEY_CHECKS = 0;\n\n");

    // Drop in REVERSE dependency order so nothing is blocked by a foreign key
    foreach (array_reverse($tables) as $table) {
        $write("DROP TABLE IF EXISTS `$table`;\n");
    }
    $write("\n");

    foreach ($tables as $table) {
        $create = $pdo->query("SHOW CREATE TABLE `$table`")->fetch(PDO::FETCH_NUM);
        $write("-- ---------------------------------------------------------\n");
        $write("-- Table: $table\n");
        $write("-- ---------------------------------------------------------\n");
        $write($create[1] . ";\n\n");

        $columns = [];
        foreach ($pdo->query("SHOW COLUMNS FROM `$table`")->fetchAll() as $col) {
            $columns[] = '`' . $col['Field'] . '`';
        }
        $columnList = implode(', ', $columns);

        $stmt = $pdo->query("SELECT * FROM `$table`");
        $batch = [];
        $rowsInTable = 0;

        while ($row = $stmt->fetch(PDO::FETCH_NUM)) {
            $values = array_map(function ($v) use ($pdo) { return backup_sql_value($pdo, $v); }, $row);
            $batch[] = '(' . implode(', ', $values) . ')';
            $rowsInTable++;

            // Flush in batches: keeps each INSERT a sensible size for
            // phpMyAdmin's import limits and keeps memory flat.
            if (count($batch) >= 100) {
                $write("INSERT INTO `$table` ($columnList) VALUES\n" . implode(",\n", $batch) . ";\n");
                $batch = [];
            }
        }
        if ($batch) {
            $write("INSERT INTO `$table` ($columnList) VALUES\n" . implode(",\n", $batch) . ";\n");
        }

        $write("-- $rowsInTable row(s)\n\n");
        $totalRows += $rowsInTable;
    }

    $write("SET FOREIGN_KEY_CHECKS = 1;\n");
    $write("-- End of backup ($totalRows rows across " . count($tables) . " tables)\n");

    return ['tables' => count($tables), 'rows' => $totalRows];
}
